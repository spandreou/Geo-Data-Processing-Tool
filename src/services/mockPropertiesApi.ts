function applyFilters(properties: Property[], filters: PropertyFilters): Property[] {
  return properties.filter((property) => {
    if (filters.area && filters.area !== "All Areas" && property.area !== filters.area) {
      return false;
    }
    if (filters.minPrice !== undefined && property.price < filters.minPrice) {
      return false;
    }
    if (filters.maxPrice !== undefined && property.price > filters.maxPrice) {
      return false;
    }
    if (filters.minSqm !== undefined && property.sqm < filters.minSqm) {
      return false;
    }
    if (filters.maxSqm !== undefined && property.sqm > filters.maxSqm) {
      return false;
    }
    return true;
  });
}

export async function fetchProperties(filters: PropertyFilters): Promise<Property[]> {
  await new Promise((resolve) => setTimeout(resolve, 260));
  return applyFilters(sampleProperties, filters);
}

export function getAreaOptions(): string[] {
  const uniqueAreas = Array.from(new Set(sampleProperties.map((property) => property.area)));
  uniqueAreas.sort((left, right) => left.localeCompare(right));
  return ["All Areas", ...uniqueAreas];
}
